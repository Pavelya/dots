package dots.campaign

import dots.ai.AiConfig

/**
 * The level ladder. These are first drafts: the difficulty curve is meant to be tuned by playing
 * (and with `cli bench levels`), not by reading the numbers.
 *
 * Every level starts the human with dots in the middle of the board. Dots on the border can never
 * be captured, so without that a player could place every dot on the border and never lose.
 */
object Campaign {
    /** An empty square board with the standard cross opening in the middle. */
    private fun crossStart(size: Int): String {
        val rows = List(size) { CharArray(size) { '.' } }
        val c = (size - 2) / 2
        rows[c][c] = 'R'
        rows[c + 1][c + 1] = 'R'
        rows[c][c + 1] = 'B'
        rows[c + 1][c] = 'B'
        return rows.joinToString("\n") { String(it) }
    }

    val levels: List<Level> = listOf(
        Level(1, "Warm-up", crossStart(8), dotsPerPlayer = 10, ai = AiConfig.EASY),
        Level(2, "Open Field", crossStart(10), dotsPerPlayer = 14, ai = AiConfig.EASY),
        Level(
            3, "Scout",
            """
            ..........
            ..........
            ..........
            ......B...
            ....RB....
            ....BR....
            ...B......
            ..........
            ..........
            ..........
            """,
            dotsPerPlayer = 14, ai = AiConfig.EASY,
        ),
        Level(
            4, "Outpost",
            """
            ...........
            ...........
            ...........
            ....B......
            ....B......
            ....B.B....
            ...........
            ......RB...
            ......BR...
            ...........
            ...........
            """,
            dotsPerPlayer = 16, ai = AiConfig.NORMAL,
        ),
        Level(
            5, "Rescue",
            """
            ............
            ............
            ..........B.
            ............
            ......B.....
            .....BRB....
            ............
            ............
            ..B.........
            ...B........
            ............
            ............
            """,
            dotsPerPlayer = 18, ai = AiConfig.NORMAL,
        ),
        Level(
            6, "Pincer",
            """
            ............
            ............
            ..B.........
            ...B........
            ............
            .....BR.....
            .....RB.....
            ........B...
            .........B..
            ...B....B...
            ............
            ............
            """,
            dotsPerPlayer = 18, ai = AiConfig.HARD,
        ),
        Level(
            7, "Siege",
            """
            .............
            .............
            .............
            ...B.B.......
            ..B...B......
            .............
            .B....R....B.
            .....R.......
            .............
            ..B...B......
            ...B.B.......
            .............
            .............
            """,
            dotsPerPlayer = 20, ai = AiConfig.HARD,
        ),
        Level(
            8, "Grandmaster",
            """
            ..............
            ..............
            ....B..B......
            ..............
            ..B....B.B....
            ..............
            ...R..B..B....
            .........R....
            ..B.....B.....
            ..............
            ....B..B.B....
            ..............
            ......B..B....
            ..............
            """,
            dotsPerPlayer = 24, ai = AiConfig.HARD,
        ),
    )

    fun level(id: Int): Level = levels.firstOrNull { it.id == id }
        ?: throw NoSuchElementException("No level $id (1..${levels.size})")
}
