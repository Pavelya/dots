package dots.campaign

import dots.ai.AiConfig

/**
 * The level ladder. These are first drafts: the difficulty curve is meant to be tuned by playing
 * (and with `dots-cli bench levels`), not by reading the numbers.
 */
object Campaign {
    private fun empty(size: Int) = List(size) { ".".repeat(size) }.joinToString("\n")

    val levels: List<Level> = listOf(
        Level(1, "Warm-up", empty(8), dotsPerPlayer = 10, ai = AiConfig.EASY),
        Level(2, "Open Field", empty(10), dotsPerPlayer = 14, ai = AiConfig.EASY),
        Level(
            3, "Scout",
            """
            ..........
            ..........
            ..........
            ..........
            ....B.....
            .....B....
            ..........
            ..........
            ..........
            ..........
            """,
            dotsPerPlayer = 14, ai = AiConfig.NORMAL,
        ),
        Level(
            4, "Outpost",
            """
            ...........
            ...........
            ...........
            ....B......
            ....B......
            ....B.B....
            ...........
            ...........
            ...........
            ...........
            ...........
            """,
            dotsPerPlayer = 16, ai = AiConfig.NORMAL,
        ),
        Level(
            5, "Rescue",
            """
            ............
            ............
            ..........B.
            ............
            ......B.....
            .....BRB....
            ............
            ............
            ..B.........
            ...B........
            ............
            ............
            """,
            dotsPerPlayer = 18, ai = AiConfig.NORMAL,
        ),
        Level(
            6, "Pincer",
            """
            ............
            ............
            ..B.........
            ...B........
            ............
            .....B......
            ............
            ........B...
            .........B..
            ........B...
            ............
            ............
            """,
            dotsPerPlayer = 18, ai = AiConfig.HARD,
        ),
        Level(
            7, "Siege",
            """
            .............
            .............
            .............
            ...B.B.......
            ..B...B......
            .............
            .B....R....B.
            .....R.......
            .............
            ..B...B......
            ...B.B.......
            .............
            .............
            """,
            dotsPerPlayer = 20, ai = AiConfig.HARD,
        ),
        Level(
            8, "Grandmaster",
            """
            ..............
            ..............
            ....B..B......
            ..............
            ..B....B.B....
            ..............
            ...R..B..B....
            .........R....
            ..B.....B.....
            ..............
            ....B..B.B....
            ..............
            ......B..B....
            ..............
            """,
            dotsPerPlayer = 24, ai = AiConfig.EXPERT,
        ),
    )

    fun level(id: Int): Level = levels.firstOrNull { it.id == id }
        ?: throw NoSuchElementException("No level $id (1..${levels.size})")
}
